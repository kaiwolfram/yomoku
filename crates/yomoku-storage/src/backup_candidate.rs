//! Private restore staging and structural/schema checks, never restore authority.

use std::{
    error::Error,
    fmt,
    fs::{File, OpenOptions},
    io::{self, Read, Write},
    path::Path,
};

use rusqlite::{config::DbConfig, limits::Limit, Connection, OpenFlags};

use crate::{backup_snapshot::StagingDirectory, migrate, SnapshotError, MIGRATIONS};

