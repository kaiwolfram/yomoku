/// Fixed diagnostics: never include candidate SQL, paths or user content.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CandidateError {
    Io(io::ErrorKind),
    Sqlite,
    InvalidDatabase,
    InvalidData,
    UnsupportedSchema,
    Cancelled,
}

impl fmt::Display for CandidateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Io(_) => "backup candidate I/O failed",
            Self::Sqlite => "backup candidate SQLite operation failed",
            Self::InvalidDatabase => "backup candidate structure or schema is invalid",
            Self::InvalidData => "backup candidate application data is invalid",
            Self::UnsupportedSchema => "backup candidate schema is unsupported",
            Self::Cancelled => "backup candidate check cancelled",
        })
    }
}

impl Error for CandidateError {}

impl From<io::Error> for CandidateError {
    fn from(error: io::Error) -> Self {
        Self::Io(error.kind())
    }
}

impl From<rusqlite::Error> for CandidateError {
    fn from(_: rusqlite::Error) -> Self {
        Self::Sqlite
    }
}

/// Write-only disposable destination for authenticated decryption. The directory
/// must be NEW, inside an app-private parent excluded from OS backup. No caller
/// file is adopted, no SQL is run while streaming, and no live database is opened.
/// Drop/failure cleans best effort; explicit discard reports cleanup errors.
/// Runtime must still clean abandoned private directories after process death.
pub struct BackupCandidate {
    file: Option<File>,
    staging: StagingDirectory,
}

impl BackupCandidate {
    pub fn create(directory: impl AsRef<Path>) -> Result<Self, CandidateError> {
        let staging =
            StagingDirectory::create(directory.as_ref()).map_err(|error| match error {
                SnapshotError::Io(kind) => CandidateError::Io(kind),
                _ => CandidateError::InvalidDatabase,
            })?;
        let file = OpenOptions::new().write(true).open(staging.path())?;
        Ok(Self {
            file: Some(file),
            staging,
        })
    }

    pub fn discard(mut self) -> Result<(), CandidateError> {
        drop(self.file.take());
        self.staging.cleanup()?;
        Ok(())
    }

    /// Call ONLY after decrypt_snapshot has authenticated Last, EOF and length.
    /// Supply the returned manifest values. These are rechecked against the file
    /// and the exact numbered migration journal before any private migration.
    ///
    /// Checks structural integrity, FKs and the exact schema generated by bundled
    /// migrations (including internal indexes). Only bundled migration SQL runs.
    /// Recheck after migrating and sync/close before returning an opaque result.
    /// Checks journal payloads, singletons, counters and saved vocabulary/custom
    /// entry domains, plus detached effective payloads and their receipts.
    /// Also checks canonical text ownership/order and saved position/time anchors.
    /// Validates retained analysis coverage and frozen effective text/page/analysis
    /// associations, exact paste/file hashes and format ownership, and TXT/SRT
    /// text/annotations derived from saved bytes. EPUB metadata/assets, rule
    /// provenance and other history checks are incomplete.
    /// Other application invariants are NOT yet validated: this cannot authorize
    /// confirmation, replacement, reads through Storage, or external Anki writes.
    /// Cancellation polls between synchronous calls, not inside SQL or sync.
    pub fn check_schema(
        mut self,
        authenticated_schema: u32,
        authenticated_len: u64,
        mut cancelled: impl FnMut() -> bool,
    ) -> Result<SchemaCheckedBackup, CandidateError> {
        check_cancelled(&mut cancelled)?;
        let version = usize::try_from(authenticated_schema)
            .ok()
            .filter(|version| (1..=MIGRATIONS.len()).contains(version))
            .ok_or(CandidateError::UnsupportedSchema)?;
        let file = self.file.take().expect("owned candidate file");
        file.sync_all()?;
        drop(file);
        let path = self.staging.path();
        check_header(&path, authenticated_len)?;
        check_cancelled(&mut cancelled)?;
        // READ_WRITE preserves CHECK parsing; query_only precedes schema parsing.
        // No CREATE, URI or shared-cache flags, and never Storage::open(candidate).
        let mut connection = Connection::open_with_flags(&path, OpenFlags::SQLITE_OPEN_READ_WRITE)?;
        harden(&connection)?;
        check_schema_and_data(&connection, version, &mut cancelled)?;
        check_cancelled(&mut cancelled)?;
        if version < MIGRATIONS.len() {
            connection.pragma_update(None, "query_only", false)?;
            migrate(&mut connection, MIGRATIONS).map_err(|_| CandidateError::InvalidDatabase)?;
            connection.pragma_update(None, "query_only", true)?;
            check_schema_and_data(&connection, MIGRATIONS.len(), &mut cancelled)?;
        }
        check_cancelled(&mut cancelled)?;
        connection.close().map_err(|_| CandidateError::Sqlite)?;
        let file = OpenOptions::new().write(true).open(&path)?;
        file.sync_all()?;
        drop(file);
        check_cancelled(&mut cancelled)?;
        Ok(SchemaCheckedBackup {
            staging: self.staging,
            original_schema: authenticated_schema,
        })
    }
}

impl Write for BackupCandidate {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        self.file
            .as_mut()
            .expect("owned candidate file")
            .write(bytes)
    }

    fn flush(&mut self) -> io::Result<()> {
        self.file.as_mut().expect("owned candidate file").flush()
    }
}

/// Structural preflight result only. Intentionally exposes neither a path nor a
/// connection/reader nor activation/confirmation authority. Application-level
/// validation beyond journals/control records/saved entries/detached effective
/// records/canonical text/live anchors/analysis associations/file identity and
/// TXT/SRT annotations is required before restore-ready.
pub struct SchemaCheckedBackup {
    staging: StagingDirectory,
    original_schema: u32,
}

impl SchemaCheckedBackup {
    pub fn original_schema(&self) -> u32 {
        self.original_schema
    }

    pub fn schema_version(&self) -> u32 {
        u32::try_from(MIGRATIONS.len()).expect("numbered bundled migrations")
    }

    pub fn discard(self) -> Result<(), CandidateError> {
        self.staging.cleanup()?;
        Ok(())
    }
}

fn check_cancelled(cancelled: &mut impl FnMut() -> bool) -> Result<(), CandidateError> {
    if cancelled() {
        Err(CandidateError::Cancelled)
    } else {
        Ok(())
    }
}

fn check_header(path: &Path, expected_len: u64) -> Result<(), CandidateError> {
    let mut file = File::open(path)?;
    if expected_len < 512 || file.metadata()?.len() != expected_len {
        return Err(CandidateError::InvalidDatabase);
    }
    let mut header = [0; 100];
    file.read_exact(&mut header)?;
    let page_size = match u16::from_be_bytes([header[16], header[17]]) {
        1 => 65_536_u64,
        size => u64::from(size),
    };
    let pages = u32::from_be_bytes(header[28..32].try_into().expect("header field"));
    if &header[..16] != b"SQLite format 3\0"
        || header[18..20] != [1, 1] // Self-contained rollback-mode snapshot, no WAL.
        || !(512..=65_536).contains(&page_size)
        || !page_size.is_power_of_two()
        || u64::from(pages) * page_size != expected_len
    {
        return Err(CandidateError::InvalidDatabase);
    }
    Ok(())
}

fn harden(connection: &Connection) -> Result<(), CandidateError> {
    for (config, value) in [
        (DbConfig::SQLITE_DBCONFIG_DEFENSIVE, true),
        (DbConfig::SQLITE_DBCONFIG_TRUSTED_SCHEMA, false),
        (DbConfig::SQLITE_DBCONFIG_ENABLE_TRIGGER, false),
        (DbConfig::SQLITE_DBCONFIG_ENABLE_VIEW, false),
        (DbConfig::SQLITE_DBCONFIG_ENABLE_ATTACH_CREATE, false),
        (DbConfig::SQLITE_DBCONFIG_ENABLE_ATTACH_WRITE, false),
    ] {
        if connection.set_db_config(config, value)? != value {
            return Err(CandidateError::Sqlite);
        }
    }
    // Bound parser work without reducing valid document/blob row lengths.
    for (limit, value) in [
        (Limit::SQLITE_LIMIT_SQL_LENGTH, 100_000),
        (Limit::SQLITE_LIMIT_COLUMN, 128),
        (Limit::SQLITE_LIMIT_EXPR_DEPTH, 64),
        (Limit::SQLITE_LIMIT_PARSER_DEPTH, 100),
        (Limit::SQLITE_LIMIT_COMPOUND_SELECT, 16),
        (Limit::SQLITE_LIMIT_VDBE_OP, 1_000_000),
        (Limit::SQLITE_LIMIT_ATTACHED, 0),
        (Limit::SQLITE_LIMIT_TRIGGER_DEPTH, 0),
        (Limit::SQLITE_LIMIT_WORKER_THREADS, 0),
    ] {
        connection.set_limit(limit, value)?;
    }
    connection.pragma_update(None, "query_only", true)?;
    connection.pragma_update(None, "cell_size_check", true)?;
    connection.pragma_update(None, "temp_store", "MEMORY")?;
    Ok(())
}

fn check_schema_and_data(
    connection: &Connection,
    version: usize,
    cancelled: &mut impl FnMut() -> bool,
) -> Result<(), CandidateError> {
    // Construct expected SQL from trusted migrations, never from candidate text.
    let mut reference = Connection::open_in_memory()?;
    migrate(&mut reference, &MIGRATIONS[..version]).map_err(|_| CandidateError::Sqlite)?;
    let mut expected = reference
        .prepare("SELECT type, name, tbl_name, sql FROM main.sqlite_schema ORDER BY type, name")?;
    let mut actual = connection
        .prepare("SELECT type, name, tbl_name, sql FROM main.sqlite_schema ORDER BY type, name")?;
    let mut expected_rows = expected.query([])?;
    let mut actual_rows = actual.query([])?;
    while let Some(expected) = expected_rows.next()? {
        check_cancelled(cancelled)?;
        let actual = actual_rows.next()?.ok_or(CandidateError::InvalidDatabase)?;
        // Compare borrowed SQLite values; no candidate-sized Rust allocations.
        for column in 0..4 {
            if expected.get_ref(column)? != actual.get_ref(column)? {
                return Err(CandidateError::InvalidDatabase);
            }
        }
    }
    if actual_rows.next()?.is_some() {
        return Err(CandidateError::InvalidDatabase);
    }
    // The journal is only queried after its ordinary table schema is proven.
    let mut history =
        connection.prepare("SELECT version, name FROM main.schema_migrations ORDER BY version")?;
    let mut rows = history.query([])?;
    for migration in &MIGRATIONS[..version] {
        check_cancelled(cancelled)?;
        let row = rows.next()?.ok_or(CandidateError::InvalidDatabase)?;
        if row.get::<_, i64>(0)? != migration.version
            || row
                .get_ref(1)?
                .as_str()
                .map_err(|_| CandidateError::InvalidDatabase)?
                != migration.name
        {
            return Err(CandidateError::InvalidDatabase);
        }
    }
    if rows.next()?.is_some() {
        return Err(CandidateError::InvalidDatabase);
    }
    check_cancelled(cancelled)?;
    // Only exact allowlisted CHECK/index expressions can be evaluated here.
    let mut integrity = connection.prepare("PRAGMA main.integrity_check(1)")?;
    let mut rows = integrity.query([])?;
    if rows
        .next()?
        .ok_or(CandidateError::InvalidDatabase)?
        .get_ref(0)?
        .as_str()
        .map_err(|_| CandidateError::InvalidDatabase)?
        != "ok"
        || rows.next()?.is_some()
    {
        return Err(CandidateError::InvalidDatabase);
    }
    check_cancelled(cancelled)?;
    if connection
        .prepare("PRAGMA main.foreign_key_check")?
        .query([])?
        .next()?
        .is_some()
    {
        return Err(CandidateError::InvalidDatabase);
    }
    controls::check(connection, &reference, version, cancelled)?;
    vocabulary::check(connection, version, cancelled)?;
    documents::check(connection, version, cancelled)?;
    formats::check(connection, version, cancelled)?;
    analyses::check(connection, version, cancelled)?;
    effective::check(connection, version, cancelled)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn candidate_hardening_blocks_writes_views_triggers_and_attachments() {
        let connection = Connection::open_in_memory().unwrap();
        connection
            .execute_batch(
                "CREATE TABLE counter (value INTEGER);
             INSERT INTO counter VALUES (0);
             CREATE VIEW exposed AS SELECT * FROM counter;
             CREATE TRIGGER mutate AFTER INSERT ON counter BEGIN
                 UPDATE counter SET value = 99;
             END;",
            )
            .unwrap();
        harden(&connection).unwrap();
        assert!(connection
            .execute("INSERT INTO counter VALUES (1)", [])
            .is_err());
        assert!(connection.prepare("SELECT * FROM exposed").is_err());
        assert!(!connection
            .db_config(DbConfig::SQLITE_DBCONFIG_TRUSTED_SCHEMA)
            .unwrap());
        assert!(connection
            .db_config(DbConfig::SQLITE_DBCONFIG_DEFENSIVE)
            .unwrap());
        // Migration enables only trusted SQL writes; schema triggers stay off.
        connection.pragma_update(None, "query_only", false).unwrap();
        connection
            .execute("INSERT INTO counter VALUES (1)", [])
            .unwrap();
        assert_eq!(
            connection
                .query_row("SELECT SUM(value) FROM counter", [], |row| row
                    .get::<_, i64>(0))
                .unwrap(),
            1
        );
        assert!(connection
            .execute_batch("ATTACH ':memory:' AS extra")
            .is_err());
        assert!(connection
            .execute_batch("PRAGMA writable_schema=ON; DELETE FROM sqlite_schema")
            .is_err());
    }
}
